use serde_json::{Value, json};

fn value(p: &Value, key: &str) -> String {
    match &p[key] {
        Value::String(s) => s.clone(),
        Value::Array(a) => a
            .iter()
            .map(|v| v.as_str().map(str::to_owned).unwrap_or_else(|| v.to_string()))
            .collect::<Vec<_>>()
            .join(", "),
        Value::Null => String::new(),
        Value::Object(o) => o.get("fallback").and_then(Value::as_str).unwrap_or_default().to_owned(),
        v => v.to_string(),
    }
}

pub fn msg(key: &str, p: Value) -> Value {
    let fallback = text(key, &p);
    json!({"key": key, "params": p, "fallback": fallback})
}

