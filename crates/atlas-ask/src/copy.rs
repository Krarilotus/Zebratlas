/// Plain labels nested in coverage messages; no English phrases travel as parameters.
pub fn need(label: &str) -> Value {
    let kind = match label {
        "patient groups or expert centres" => "groups",
        "studies" => "studies",
        "papers" => "papers",
        "NIH research projects" => "grants",
        "patient group" => "patient_group",
        "open study or registry" => "open_study",
        "researcher" => "researcher",
        "research project" => "project",
        _ => panic!("unknown need label"),
    };
    msg(&format!("ask.need.{kind}"), json!({}))
}
